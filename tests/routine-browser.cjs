    assert.equal(state.schemaVersion, 2); assert.equal(state.cars[0].usage, 'severe');
    assert.deepEqual(state.cars[0].intervals['engine-oil'], { km: 8000, months: 4 });
    assert.equal(state.records.length, 3); assert.equal(state.records.filter(record => record.serviceItems.includes('engine-oil')).length, 2);
    await mkdir('test-results', { recursive: true });
