const assert = require('node:assert/strict');
const { readFile, mkdir } = require('node:fs/promises');
const { chromium } = require(process.env.BROWSER_TEST_PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const url = process.env.BROWSER_TEST_URL || 'http://localhost:4173';
    await page.goto(url);
    const dates = await page.evaluate(async () => {
      const { localDate } = await import('./src/maintenance-model.js');
      const future = new Date(); future.setDate(future.getDate() + 60);
      return { today: localDate(), future: localDate(future) };
    });
    const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('combustivel-inteligente-revisoes-v1')));
    const submitCar = async () => { await page.locator('#car-form button[type=submit]').click(); await page.waitForFunction(() => !document.querySelector('#car-form [type=submit]').disabled); };
    const submitService = async () => { await page.locator('#maintenance-form button[type=submit]').click(); await page.waitForFunction(() => !document.querySelector('#maintenance-form [type=submit]').disabled); };
    assert.equal(await page.locator('#garage-empty').isVisible(), true);
    await page.locator('#add-car').click();
    await page.locator('#car-name').fill('Meu Onix 2022');
    await page.locator('#car-odometer').fill('50000'); await submitCar();
    const carA = (await stored()).selectedCar;
    await page.locator('#add-maintenance').click();
    await page.locator('#service-date').fill('2999-01-01');
    await page.locator('#service-description').fill('Óleo e filtro'); await submitService();
    assert.equal(await page.locator('#service-error').isVisible(), true);
    assert.equal((await stored()).records.length, 0);
    await page.locator('#service-date').fill(dates.today);
    await page.locator('#service-description').fill('Troca de óleo e filtro\n<img src=x onerror="window.injected=true">');
    await page.locator('#service-cost').fill('450,50');
    await page.locator('#service-workshop').fill('Oficina do bairro');
    await page.locator('#service-notes').fill('Óleo 5W30 · guardar nota fiscal');
    await page.locator('#service-next-date').fill(dates.future);
    await page.locator('#service-next-km').fill('60000'); await submitService();
    assert.equal((await stored()).records.length, 1);
    assert.match(await page.locator('#maintenance-total').innerText(), /450,50/);
    assert.ok((await page.locator('#next-maintenance').getAttribute('class')).includes('scheduled'));
    assert.equal(await page.locator('#maintenance-list img').count(), 0);
    assert.equal(await page.evaluate(() => window.injected), undefined);
    await page.locator('[data-action=edit]').click();
    await page.locator('#service-cost').fill('500'); await submitService();
    assert.match(await page.locator('#maintenance-total').innerText(), /500,00/);
    await page.locator('#edit-car').click(); await page.locator('#car-odometer').fill('40000'); await submitCar();
    assert.equal(await page.locator('#car-error').isVisible(), true);
    assert.equal((await stored()).cars[0].odometer, 50000);
    await page.locator('#car-odometer').fill('59000'); await submitCar();
    assert.ok((await page.locator('#next-maintenance').getAttribute('class')).includes('soon'));
    await page.locator('#edit-car').click(); await page.locator('#car-odometer').fill('60000'); await submitCar();
    assert.ok((await page.locator('#next-maintenance').getAttribute('class')).includes('due'));
    await page.locator('#add-car').click(); await page.locator('#car-name').fill('Outro Onix 2022'); await submitCar();
    assert.equal(await page.locator('.service-record').count(), 0);
    await page.locator('#garage-car').selectOption(carA);
    await page.waitForFunction(() => document.querySelectorAll('.service-record').length === 1);
    assert.equal(await page.locator('.service-record').count(), 1);
    await page.reload(); assert.equal(await page.locator('.service-record').count(), 1);
    const downloadPromise = page.waitForEvent('download'); await page.locator('#export-maintenance').click();
    const download = await downloadPromise;
    const backup = JSON.parse(await readFile(await download.path(), 'utf8'));
    assert.equal(backup.cars.length, 2); assert.equal(backup.records.length, 1);
    const upload = json => page.locator('#backup-file').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(json)) });
    const stateBefore = await stored();
    await upload({ schemaVersion: 2, cars: [], records: [] });
    await page.waitForFunction(() => document.getElementById('maintenance-status').textContent.includes('Não foi possível importar'));
    assert.deepEqual(await stored(), stateBefore);
    await upload(backup);
    await page.waitForFunction(() => document.getElementById('maintenance-status').textContent.includes('0 carros adicionados e 0 revisões adicionadas'));
    assert.equal((await stored()).records.length, 1);
    // Import restores an independent browser's empty garage without duplication.
    const other = await browser.newContext(); const otherPage = await other.newPage(); await otherPage.goto(url);
    await otherPage.locator('#backup-file').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
    await otherPage.waitForFunction(() => document.querySelectorAll('.service-record').length === 1);
    assert.match(await otherPage.locator('#maintenance-total').innerText(), /500,00/);
    await other.close();
    // Storage failures must never report a successful save or remove old data.
    await page.evaluate(() => {
      window.originalSetItem = Storage.prototype.setItem;
      Storage.prototype.setItem = function (key, value) {
        if (key === 'combustivel-inteligente-revisoes-v1') throw new DOMException('Full', 'QuotaExceededError');
        return window.originalSetItem.call(this, key, value);
      };
    });
    await page.locator('[data-action=edit]').click(); await page.locator('#service-cost').fill('700'); await submitService();
    assert.match(await page.locator('#service-error').innerText(), /Não foi possível salvar/);
    assert.equal((await stored()).records[0].cost, 500);
    await page.locator('[data-close-dialog=maintenance-dialog]').click();
    await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
    await page.locator('[data-action=delete]').click();
    await page.locator('#maintenance-confirm button[data-close-dialog]').first().click();
    assert.equal((await stored()).records.length, 1);
    await page.locator('[data-action=delete]').click(); await page.locator('#confirm-maintenance-delete').click();
    await page.waitForFunction(() => !document.getElementById('maintenance-confirm').open);
    assert.equal((await stored()).records.length, 0);
    await upload(backup); await page.waitForFunction(() => document.querySelectorAll('.service-record').length === 1);
    // A stale edit must not overwrite a revision changed by another tab.
    await page.locator('[data-action=edit]').click();
    const second = await context.newPage(); await second.goto(url);
    await second.locator('[data-action=edit]').click(); await second.locator('#service-cost').fill('650');
    await second.locator('#maintenance-form button[type=submit]').click();
    await second.waitForFunction(() => !document.getElementById('maintenance-dialog').open);
    await page.locator('#service-cost').fill('750'); await submitService();
    assert.match(await page.locator('#service-error').innerText(), /alterada em outra aba/);
    assert.equal((await stored()).records[0].cost, 650);
    await page.locator('[data-close-dialog=maintenance-dialog]').click(); await second.close();
    await mkdir('test-results', { recursive: true });
    await page.locator('#revisoes').screenshot({ path: 'test-results/revisoes-desktop.png' });
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `overflow at ${width}`);
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#revisoes').screenshot({ path: 'test-results/revisoes-mobile.png' });
    await page.evaluate(() => navigator.serviceWorker.ready);
    await page.waitForFunction(() => navigator.serviceWorker.controller !== null);
    await context.setOffline(true); await page.reload();
    assert.equal(await page.locator('.service-record').count(), 1);
    await page.locator('[data-action=edit]').click(); await page.locator('#service-cost').fill('675'); await submitService();
    assert.equal((await stored()).records[0].cost, 675);
    await page.reload(); assert.match(await page.locator('#maintenance-total').innerText(), /675,00/);
    await context.setOffline(false);
    const concurrent = await context.newPage(); await concurrent.goto(url);
    await page.locator('#add-maintenance').click(); await page.locator('#service-description').fill('Alinhamento'); await page.locator('#service-cost').fill('10');
    await concurrent.locator('#add-maintenance').click(); await concurrent.locator('#service-description').fill('Filtro de ar'); await concurrent.locator('#service-cost').fill('20');
    await Promise.all([submitService(), concurrent.locator('#maintenance-form button[type=submit]').click()]);
    await concurrent.waitForFunction(() => !document.getElementById('maintenance-dialog').open);
    assert.equal((await stored()).records.length, 3); await concurrent.close();
    await page.locator('#delete-car').click(); await page.locator('#confirm-maintenance-delete').click();
    await page.waitForFunction(() => !document.getElementById('maintenance-confirm').open);
    assert.equal((await stored()).cars.length, 1); assert.equal((await stored()).records.length, 0);
    await page.evaluate(() => localStorage.setItem('combustivel-inteligente-revisoes-v1', '{broken'));
    await page.reload();
    assert.equal(await page.locator('#add-car').isDisabled(), true);
    assert.match(await page.locator('#maintenance-status').innerText(), /Nenhum registro será sobrescrito/);
    assert.match(await page.locator('#total-cost').innerText(), /41,98/);
    const rawDownloadPromise = page.waitForEvent('download'); await page.locator('#export-maintenance').click();
    assert.equal(await readFile(await (await rawDownloadPromise).path(), 'utf8'), '{broken');
    assert.equal(await page.evaluate(() => localStorage.getItem('combustivel-inteligente-revisoes-v1')), '{broken');
    assert.deepEqual(errors, []);
    console.log('Passed maintenance: create/edit cars and services, isolated histories, validation, reminders, backups, failed writes, delete/cancel/cascade, concurrent edits and additions, corrupt storage recovery, 4 widths and offline save/reload.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
